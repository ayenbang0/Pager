// Regenerates src/remote/webAssets.ts: the web client of `pager serve` (src/remote/client/*) plus the desktop's tokens.css and the
// vendored xterm.js, gzipped and base64 encoded into one module, so the server needs no files at run time.
// Run it after editing any of those inputs:  node scripts/gen-remote-assets.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import zlib from 'node:zlib'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const vendor = path.join(root, 'desktop/renderer/vendor')
const JS = 'text/javascript; charset=utf-8'
const CSS = 'text/css; charset=utf-8'

const inputs = {
  '/': ['text/html; charset=utf-8', path.join(root, 'src/remote/client/index.html')],
  '/assets/app.js': [JS, path.join(root, 'src/remote/client/app.js')],
  '/assets/app.css': [CSS, path.join(root, 'src/remote/client/app.css')],
  '/assets/tokens.css': [CSS, path.join(root, 'desktop/renderer/ui/tokens.css')],
  '/assets/xterm.js': [JS, path.join(vendor, 'xterm.js')],
  '/assets/xterm.css': [CSS, path.join(vendor, 'xterm.css')],
  '/assets/addon-fit.js': [JS, path.join(vendor, 'addon-fit.js')],
}

let out = `// GENERATED by scripts/gen-remote-assets.mjs from src/remote/client/*, desktop/renderer/ui/tokens.css and desktop/renderer/vendor/*. Do not edit.
// Each asset is gzipped and base64 encoded; the server inflates it for clients that do not accept gzip.
// xterm.js is MIT licensed (see desktop/renderer/vendor/LICENSE-xterm.txt).

export interface WebAsset {
  type: string
  gzip: string
}

export const WEB_ASSETS: Record<string, WebAsset> = {
`
for (const [route, [type, file]] of Object.entries(inputs)) {
  const gz = zlib.gzipSync(fs.readFileSync(file), { level: 9 })
  out += `  ${JSON.stringify(route)}: { type: ${JSON.stringify(type)}, gzip: '${gz.toString('base64')}' },\n`
}
out += '}\n'
fs.writeFileSync(path.join(root, 'src/remote/webAssets.ts'), out)
console.log(`src/remote/webAssets.ts: ${Object.keys(inputs).length} assets, ${(out.length / 1024).toFixed(0)} KiB`)
