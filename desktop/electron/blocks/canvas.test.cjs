test('the file changing behind our back is merged in (mtime check) and announced', async () => {
  const dir = tmp()
  const ctx = mkctx(dir)
  await call('open', { id: 'ext' }, ctx)
  await call('save', { id: 'ext', baseSeq: 0, doc: { shapes: [rect('a'), rect('b', 200)] } }, ctx)
  await call('flush', { id: 'ext' }, ctx)
  const file = path.join(dir, 'ext.canvas.json')
  // the window changes a (not yet on disk) ...
  const s = await call('save', { id: 'ext', baseSeq: 1, doc: { shapes: [rect('a', 33), rect('b', 200)] } }, ctx)
  assert.equal(s.ok, true)
  // ... while an external tool edits the file: moves b, adds c
  const disk = JSON.parse(fs.readFileSync(file, 'utf8'))
  disk.shapes[1].x = 999
  disk.shapes.push(rect('c', 0, 400))
  fs.writeFileSync(file, JSON.stringify(disk))
  const future = new Date(Date.now() + 5000)
  fs.utimesSync(file, future, future)
  ctx.events.length = 0
  await call('flush', { id: 'ext' }, ctx)
  const r = await call('read', { id: 'ext' }, ctx)
  const by = Object.fromEntries(r.shapes.map((x) => [x.id, x]))
  assert.equal(by.a.x, 33, 'local edit kept')
  assert.equal(by.b.x, 999, 'external edit kept')
  assert.ok(by.c, 'external addition kept')
  assert.ok(r.seq >= 3)
  const changed = ctx.events.find((e) => e.event === 'changed')
  assert.ok(changed, 'the window is told')
  assert.equal(changed.payload.source, 'disk')
  assert.equal(JSON.parse(fs.readFileSync(file, 'utf8')).shapes.length, 3, 'and the merged result is on disk')
  // an external edit that lands before the window saves turns that save into a conflict to merge
  const again = JSON.parse(fs.readFileSync(file, 'utf8'))
  again.shapes[2].y = 777
  fs.writeFileSync(file, JSON.stringify(again))
  const later = new Date(Date.now() + 9000)
  fs.utimesSync(file, later, later)
  const stale = await call('save', { id: 'ext', baseSeq: r.seq, doc: { shapes: r.shapes } }, ctx)
  assert.equal(stale.ok, false)
  assert.equal(stale.conflict, true)
  assert.equal(stale.doc.shapes.find((x) => x.id === 'c').y, 777)
})

