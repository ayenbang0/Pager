'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')

process.env.PAGER_CANVAS_SHOT_TIMEOUT = '150'
const canvas = require('./canvas.cjs')
const { methods, _t } = canvas

const tmp = () => fs.mkdtempSync(path.join(os.tmpdir(), 'pager-canvas-'))
const PNG = Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), Buffer.alloc(40, 1)])
const mkctx = (dir) => {
  const events = []
  return { canvasDir: dir, emit: (event, payload) => events.push({ event, payload }), events }
}
const rect = (id, x = 0, y = 0, extra = {}) => ({ id, type: 'rect', x, y, w: 100, h: 60, seed: 1, ...extra })
const call = (name, args, ctx) => methods[name](args, ctx)
const ids = (doc) => doc.shapes.map((s) => s.id)

test.beforeEach(() => _t.reset())
test.after(() => _t.reset())

test('the model loads from source (relative imports inlined)', async () => {
  const M = await _t.loadModel()
  assert.equal(typeof M.applyOps, 'function')
  assert.equal(typeof M.mergeShapes, 'function')
  assert.equal(M.VERSION, 1)
})

test('open creates an empty canvas lazily; first save writes `<id>.canvas.json` atomically', async () => {
  const dir = tmp()
  const ctx = mkctx(dir)
  const o = await call('open', { id: 'board' }, ctx)
  assert.equal(o.id, 'board')
  assert.equal(o.seq, 0)
  assert.equal(o.doc.shapes.length, 0)
  assert.equal(fs.existsSync(path.join(dir, 'board.canvas.json')), false, 'nothing written until there is something to save')
  const s = await call('save', { id: 'board', baseSeq: 0, doc: { shapes: [rect('a')], view: { x: 5, y: 6, zoom: 2 } }, label: 'Add rectangle' }, ctx)
  assert.deepEqual([s.ok, s.seq], [true, 1])
  assert.equal(fs.existsSync(path.join(dir, 'board.canvas.json')), false, 'debounced: not yet on disk')
  await call('flush', { id: 'board' }, ctx)
  const file = path.join(dir, 'board.canvas.json')
  const disk = JSON.parse(fs.readFileSync(file, 'utf8'))
  assert.equal(disk.seq, 1)
  assert.equal(disk.shapes[0].id, 'a')
  assert.equal(disk.view.zoom, 2)
  assert.equal(disk.edits[0].label, 'Add rectangle')
  assert.deepEqual(fs.readdirSync(dir).filter((f) => f.endsWith('.tmp')), [])
  // a fresh process (cleared state) reads it back
  _t.reset()
  const again = await call('open', { id: 'board' }, ctx)
  assert.equal(again.seq, 1)
  assert.deepEqual(ids(again.doc), ['a'])
  assert.equal(again.doc.view.x, 5)
  const hist = await call('history', { id: 'board' }, ctx)
  assert.equal(hist.edits.length, 1, 'the edit log survives a restart')
})

