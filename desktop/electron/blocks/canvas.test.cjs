test('stale saves are refused with the current document; merging resolves them', async () => {
  const ctx = mkctx(tmp())
  await call('open', { id: 'c', ephemeral: true }, ctx)
  await call('save', { id: 'c', baseSeq: 0, doc: { shapes: [rect('a')] } }, ctx)
  const e = await call('edit', { id: 'c', ops: [{ op: 'add', shape: rect('agent', 300, 0) }] }, ctx)
  assert.equal(e.ok, true)
  assert.equal(e.seq, 2)
  const stale = await call('save', { id: 'c', baseSeq: 1, doc: { shapes: [rect('a', 50, 0), rect('mine', 0, 200)] } }, ctx)
  assert.equal(stale.ok, false)
  assert.equal(stale.conflict, true)
  assert.equal(stale.seq, 2)
  assert.deepEqual(ids(stale.doc), ['a', 'agent'])
  const M = await _t.loadModel()
  const merged = M.mergeShapes(M.normalizeDoc({ shapes: [rect('a')] }).shapes, [rect('a', 50, 0), rect('mine', 0, 200)].map((s) => M.parseShape(s)), stale.doc.shapes)
  const ok = await call('save', { id: 'c', baseSeq: 2, doc: { shapes: merged } }, ctx)
  assert.equal(ok.ok, true)
  const r = await call('read', { id: 'c' }, ctx)
  assert.deepEqual(r.shapes.map((s) => s.id).sort(), ['a', 'agent', 'mine'])
  assert.equal(r.shapes.find((s) => s.id === 'a').x, 50)
  await assert.rejects(call('save', { id: 'c', doc: { shapes: [] } }, ctx), /baseSeq/)
  await assert.rejects(call('save', { id: 'c', baseSeq: 3, doc: {} }, ctx), /doc.shapes/)
})

