test('edit: add / update / remove / group / layout, with ids, history and a `changed` event', async () => {
  const ctx = mkctx(tmp())
  await call('open', { id: 'e', ephemeral: true }, ctx)
  const r = await call('edit', {
    id: 'e',
    ops: [
      { op: 'add', shape: { id: 'one', type: 'rect', x: 0, y: 0, w: 100, h: 60, text: 'One' } },
      { op: 'add', shape: { id: 'two', type: 'ellipse', x: 300, y: 80, w: 100, h: 60, text: 'Two' } },
      { op: 'add', shape: { id: 'link', type: 'arrow', x1: 0, y1: 0, x2: 1, y2: 1, from: 'one', to: 'two' } },
    ],
  }, ctx)
  assert.equal(r.ok, true)
  assert.deepEqual(r.created, ['one', 'two', 'link'])
  assert.equal(r.seq, 1)
  const ev = ctx.events.find((x) => x.event === 'changed')
  assert.equal(ev.payload.source, 'agent')
  assert.deepEqual(ev.payload.ids.created, ['one', 'two', 'link'])
  assert.equal(ev.payload.doc.shapes.length, 3)
  const u = await call('edit', { id: 'e', ops: [{ op: 'update', id: 'one', set: { fill: 'rgba(61,111,255,.22)', text: 'Uno' } }, { op: 'group', ids: ['one', 'two'], id: 'pair' }] }, ctx)
  assert.deepEqual(u.changed.sort(), ['one', 'two'])
  const lay = await call('edit', { id: 'e', ops: [{ op: 'layout', kind: 'tree', ids: ['one', 'two', 'link'] }] }, ctx)
  assert.equal(lay.ok, true)
  const rm = await call('edit', { id: 'e', ops: [{ op: 'remove', ids: ['two'] }] }, ctx)
  assert.deepEqual(rm.removed, ['two'])
  const read = await call('read', { id: 'e' }, ctx)
  assert.equal(read.shapes.find((s) => s.id === 'link').bind.e, undefined, 'the arrow lost its target')
  const h = await call('history', { id: 'e', limit: 2 }, ctx)
  assert.equal(h.edits.length, 2)
  assert.equal(h.edits[1].source, 'agent')
  assert.deepEqual(h.edits[1].removed, ['two'])
  assert.deepEqual(h.edits[0].n + 1, h.edits[1].n)
  const all = await call('history', { id: 'e' }, ctx)
  assert.deepEqual(all.edits.map((x) => x.created.length), [3, 0, 0, 0].slice(0, all.edits.length))
  assert.match(all.edits[0].label, /^Agent: \+3/)
})

test('edit is atomic and returns every validation error; expectSeq detects races', async () => {
  const ctx = mkctx(tmp())
  await call('open', { id: 'bad', ephemeral: true }, ctx)
  await call('edit', { id: 'bad', ops: [{ op: 'add', shape: rect('a') }] }, ctx)
  ctx.events.length = 0
  const r = await call('edit', {
    id: 'bad',
    ops: [{ op: 'add', shape: { type: 'rect', x: 'left' } }, { op: 'update', id: 'a', set: { stroke: 'javascript:alert(1)' } }, { op: 'add', shape: { type: 'rect', hax: true } }, { op: 'nope' }],
  }, ctx)
  assert.equal(r.ok, false)
  assert.deepEqual(r.errors.map((e) => e.index), [0, 1, 2, 3])
  assert.match(r.errors[0].error, /x: must be a finite number/)
  assert.deepEqual(ctx.events, [], 'nothing changed, nothing emitted')
  assert.equal((await call('read', { id: 'bad' }, ctx)).count, 1)
  const raced = await call('edit', { id: 'bad', expectSeq: 0, ops: [{ op: 'clear' }] }, ctx)
  assert.equal(raced.ok, false)
  assert.equal(raced.conflict, true)
  const nonArray = await call('edit', { id: 'bad', ops: 'clear' }, ctx)
  assert.equal(nonArray.ok, false)
  const noop = await call('edit', { id: 'bad', ops: [] }, ctx)
  assert.equal(noop.ok, true)
  assert.equal(noop.seq, 1, 'an empty edit does not bump the seq')
})

