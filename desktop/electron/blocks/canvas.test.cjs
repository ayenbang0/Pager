test('shot: round trip through the window, validation, and the no-window timeout', async () => {
  const ctx = mkctx(tmp())
  await call('open', { id: 's', ephemeral: true }, ctx)
  ctx.emit = (event, payload) => {
    ctx.events.push({ event, payload })
    if (event === 'shot') setImmediate(() => call('shotReply', { req: payload.req, dataUrl: 'data:image/png;base64,AAAA', width: payload.width || 800, height: 600 }))
  }
  const r = await call('shot', { id: 's', fit: 'content', width: 640 }, ctx)
  assert.equal(r.mime, 'image/png')
  assert.equal(r.dataUrl, 'data:image/png;base64,AAAA')
  assert.equal(r.width, 640)
  const req = ctx.events.find((e) => e.event === 'shot').payload
  assert.deepEqual([req.id, req.fit, req.width, req.scale], ['s', 'content', 640, 1])
  await assert.rejects(call('shot', { id: 's', fit: 'zoom' }, ctx), /fit must be/)
  await assert.rejects(call('shot', { id: 's', width: 10 }, ctx), /width must be/)
  await assert.rejects(call('shot', { id: 's', scale: 9 }, ctx), /scale must be/)
  // an error from the window
  ctx.emit = (event, payload) => event === 'shot' && setImmediate(() => call('shotReply', { req: payload.req, error: 'render failed' }))
  await assert.rejects(call('shot', { id: 's' }, ctx), /render failed/)
  // a hostile reply
  ctx.emit = (event, payload) => event === 'shot' && setImmediate(() => call('shotReply', { req: payload.req, dataUrl: 'javascript:alert(1)' }))
  await assert.rejects(call('shot', { id: 's' }, ctx), /bad screenshot reply/)
  // nobody answers
  ctx.emit = () => {}
  await assert.rejects(call('shot', { id: 's' }, ctx), (e) => e.code === 'NOT_OPEN')
  assert.deepEqual(await call('shotReply', { req: 'nope' }), { ok: false })
})

test('images: stored by hash, validated by magic bytes, required by edit', async () => {
  const dir = tmp()
  const ctx = mkctx(dir)
  await call('open', { id: 'img' }, ctx)
  const put = await call('putBlob', { id: 'img', mime: 'image/png', data: PNG.toString('base64') }, ctx)
  assert.match(put.hash, /^[a-f0-9]{32}$/)
  assert.equal(put.bytes, PNG.length)
  const again = await call('putBlob', { id: 'img', mime: 'image/png', data: PNG.toString('base64') }, ctx)
  assert.equal(again.hash, put.hash, 'content addressed: idempotent')
  assert.ok(fs.existsSync(path.join(dir, 'img.blobs', `${put.hash}.png`)))
  const got = await call('getBlob', { id: 'img', hash: put.hash }, ctx)
  assert.equal(got.mime, 'image/png')
  assert.equal(Buffer.from(got.data, 'base64').equals(PNG), true)
  await assert.rejects(call('putBlob', { id: 'img', mime: 'image/png', data: Buffer.from('<svg onload=alert(1)>').toString('base64') }, ctx), /not a image\/png/)
  await assert.rejects(call('putBlob', { id: 'img', mime: 'image/svg+xml', data: 'AAAA' }, ctx), /mime must be/)
  await assert.rejects(call('putBlob', { id: 'img', mime: 'image/png', data: 'A'.repeat(40e6) }, ctx), /limited to/)
  await assert.rejects(call('getBlob', { id: 'img', hash: '../../etc/passwd' }, ctx), /hash must be/)
  await assert.rejects(call('getBlob', { id: 'img', hash: 'f'.repeat(32) }, ctx), /no stored image/)
  const missing = await call('edit', { id: 'img', ops: [{ op: 'add', shape: { type: 'image', hash: 'e'.repeat(32), x: 0, y: 0 } }] }, ctx)
  assert.equal(missing.ok, false)
  assert.match(missing.errors[0].error, /putBlob first/)
  const ok = await call('edit', { id: 'img', ops: [{ op: 'add', shape: { type: 'image', hash: put.hash, mime: 'image/png', x: 0, y: 0, nw: 400, nh: 200 } }] }, ctx)
  assert.equal(ok.ok, true)
  const shape = (await call('read', { id: 'img' }, ctx)).shapes[0]
  assert.deepEqual([shape.w, shape.h], [400, 200])
})

